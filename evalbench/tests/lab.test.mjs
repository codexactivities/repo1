import { test } from 'node:test';
import assert from 'node:assert/strict';
import { validateCases, evaluate, stats, gate, normalizeResults } from '../web/core.js';
import { normalizePrompt, messages, checkVariables, normalizeJudge, parseJudgment, importDataset, datasetCsv, compareRuns, calibration, textDiff, experimentBundle } from '../web/lab.js';
import { grade, validateSchema } from '../web/graders.js';
const c = { id: 'x', title: 'X', slice: 'All', tags: ['smoke'], vars: { q: 'Say yes' }, reference: 'yes', rules: [{ type: 'exact', value: 'yes' }] };
const prompt = normalizePrompt({ text: '{{q}}', model: 'mock' });
function run(a = 'yes', b = 'yes') { return { id: 'run', cases: [c], prompts: { a: prompt, b: prompt }, results: { x: { a: { text: a }, b: { text: b } } }, reviews: {} }; }
test('CSV/JSONL datasets round-trip multiline quotes, scalar variables, reference, tags and rules; reject malformed rows', () => {
    const cs = validateCases([{ ...c, title: 'Title, "quoted"', reference: 'line 1\nline 2', vars: { q: 'What, "now"?\nTwo lines', n: 4, ok: true } }]);
    assert.deepEqual(importDataset(datasetCsv(cs), 'csv'), cs);
    assert.deepEqual(importDataset(cs.map(x => JSON.stringify(x)).join('\n'), 'jsonl'), cs);
    assert.equal(importDataset('id,var.question,reference,tags\nx,hello,yes,smoke|format', 'csv')[0].vars.question, 'hello');
    assert.throws(() => importDataset('id,vars\nx,"{}', 'csv'));
    assert.throws(() => importDataset('{"id":"x"}\nbad', 'jsonl'), /2/);
    assert.throws(() => validateCases([{ ...c }, { ...c }]), /уникальный/);
});
test('all new graders evaluate actual values and explain schema/field/numeric/regex/reference failures', () => {
    const rules = [{ type: 'jsonSchema', schema: { type: 'object', required: ['amount', 'state'], properties: { amount: { type: 'number' }, state: { enum: ['OK'] } }, additionalProperties: false } }, { type: 'field', path: '/state', op: 'eq', value: 'OK' }, { type: 'number', path: 'amount', value: 42, tolerance: .1 }, { type: 'regex', pattern: '"state"\\s*:\\s*"OK"' }, { type: 'reference', mode: 'json' }];
    assert.equal(evaluate('{"state":"OK","amount":42.05}', rules, { reference: '{"amount":42.05,"state":"OK"}' }).pass, true);
    const bad = evaluate('{"state":"bad","amount":"42"}', rules, { reference: '{}' });
    assert.equal(bad.pass, false);
    assert.equal(bad.checks.filter(x => !x.pass).length, 5);
    assert.ok(bad.checks.every(x => x.reason));
    assert.equal(evaluate('a'.repeat(50000) + '!', [{ type: 'regex', pattern: '^(a+)+$' }]).pass, false);
    assert.throws(() => validateSchema({ $ref: 'https://evil.example/schema' }), /локальные/);
    assert.throws(() => validateSchema({ pattern: '(a+)+$' }), /regex/);
});
test('structured prompts render system, examples and user; reject missing variables and invalid generation parameters', () => {
    const p = normalizePrompt({ system: 'System {{q}}', user: 'Question {{q}}', examples: [{ user: 'U', assistant: 'A' }], params: { temperature: 0, top_p: .5, seed: 1 } });
    assert.equal(messages(p, c).length, 4);
    assert.equal(messages(p, c)[0].content, 'System Say yes');
    assert.equal(messages(p, c)[2].role, 'assistant');
    assert.throws(() => checkVariables(normalizePrompt({ text: '{{missing}}' }), [c]), /missing/);
    assert.throws(() => normalizePrompt({ text: 'x', params: { temperature: 3 } }));
});
test('judge strict output, weighted scoring, missing criterion errors and pending judge blocks release', () => {
    const j = normalizeJudge({ enabled: true, criteria: [{ id: 'a', description: 'A', weight: 3 }, { id: 'b', description: 'B', weight: 1 }] });
    const good = parseJudgment('{"criteria":[{"id":"a","score":4,"reason":"Correct"},{"id":"b","score":0,"reason":"Wrong"}]}', j);
    assert.equal(good.score, .75);
    assert.equal(good.pass, true);
    assert.throws(() => parseJudgment('{"criteria":[]}', j));
    assert.throws(() => parseJudgment('{"criteria":[{"id":"a","score":8,"reason":"x"},{"id":"b","score":0,"reason":"x"}]}', j));
    const r = run();
    r.judge = j;
    assert.equal(grade(r, c, 'b').pass, null);
    assert.equal(gate(r, 0).state, 'pending');
    r.judgments = [{ x: { a: good, b: good } }];
    assert.equal(gate(r, 0).state, 'pass');
    r.judgments[0].x.b = { error: 'bad JSON' };
    assert.equal(gate(r, 0).state, 'pending');
});
test('paired comparison excludes changed/ungraded cases, aggregates repetitions and computes case-clustered uncertainty', () => {
    const a = run(), b = run('yes', 'no');
    a.cases = [c, { ...c, id: 'y' }];
    b.cases = [c, { ...c, id: 'y', reference: 'changed' }];
    a.results.y = a.results.x;
    b.results.y = b.results.x;
    let x = compareRuns(a, b);
    assert.equal(x.paired, 1);
    assert.equal(x.delta, -1);
    assert.deepEqual(x.regressions, ['x']);
    assert.equal(x.excluded.length, 1);
    assert.equal(x.ci, null);
    b.cases = a.cases;
    x = compareRuns(a, b);
    assert.deepEqual(x.ci, [-1, -1]);
    assert.equal(x.verdict, 'Ухудшение подтверждается выборкой');
    b.repeats = 2;
    b.repetitions = [b.results, { x: { a: { text: 'yes' }, b: { text: 'yes' } }, y: { a: { text: 'yes' }, b: { text: 'yes' } } }];
    x = compareRuns(a, b);
    assert.equal(x.delta, -.5);
    assert.equal(stats(b, 'b').total, 4);
    assert.equal(stats(b, 'b').passed, 2);
    assert.equal(gate(b, 0).regressions, 2);
});
test('human calibration counts disagreements; diff and imported metadata remain reproducible', () => {
    const r = run();
    r.judgments = [{ x: { a: { score: .25 }, b: { score: 1 } } }];
    r.reviews = { x: { winner: 'a' } };
    assert.equal(calibration(r).agreement, 0);
    assert.equal(calibration(r).n, 1);
    assert.ok(textDiff('one two', 'one three').parts.some(x => x.type === 'del'));
    assert.equal(experimentBundle(r).version, 3);
    const imported = normalizeResults([{ id: 'x', a: { text: 'yes', responseId: 'r', usage: { prompt_tokens: 1, completion_tokens: 2, total_tokens: 3 }, cost: .001 } }], [c]);
    assert.equal(imported.x.a.usage.total_tokens, 3);
    assert.equal(imported.x.a.responseId, 'r');
});
test('comparison cannot hide removed hard cases or compare different judge rubrics as if they were the same metric', () => {
    const a = run(), b = run();
    a.cases = [c, { ...c, id: 'removed' }];
    a.results.removed = { a: { text: 'yes' }, b: { text: 'no' } };
    let x = compareRuns(a, b);
    assert.equal(x.excluded[0].id, 'removed');
    assert.equal(x.verdict, 'Неполное покрытие');
    b.judge = normalizeJudge({ enabled: true, model: 'different-judge' });
    x = compareRuns(a, b);
    assert.equal(x.gradingMismatch, true);
    assert.equal(x.paired, 0);
    assert.match(x.verdict, /Разные оценщики/);
});
test('invalid schema constraints are rejected rather than ignored; const values can contain arbitrary data keys', () => {
    assert.throws(() => validateSchema({ type: 'object', minProperties: 'two' }));
    assert.throws(() => validateSchema({ requred: ['x'] }), /requred/);
    assert.throws(() => validateSchema({ format: 'imaginary-format' }));
    assert.equal(evaluate('0', [{ type: 'number', value: 0 }]).pass, true);
    assert.equal(evaluate('  ', [{ type: 'number', value: 0 }]).pass, false);
    assert.equal(evaluate('{"type":"custom"}', [{ type: 'jsonSchema', schema: { const: { type: 'custom' } } }]).pass, true);
});
test('boolean false output schema and per-case schema are both enforced', () => {
    const r = run();
    r.prompts = { ...r.prompts, b: { ...r.prompts.b, schema: false } };
    assert.equal(grade(r, c, 'b').pass, false);
    const jsonCase = { ...c, rules: [{ type: 'jsonSchema', schema: { type: 'object' } }] };
    r.cases = [jsonCase];
    r.results.x.b.text = '{}';
    r.prompts.b.schema = { type: 'object', required: ['answer'] };
    assert.equal(grade(r, jsonCase, 'b').pass, false);
});
